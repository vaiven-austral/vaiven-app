-- ============================================
-- TABLA PUBLICACIONES
-- ============================================
CREATE TABLE public.publicaciones (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    usuario_id UUID NOT NULL REFERENCES public.perfiles(id) ON DELETE CASCADE,
    tipo TEXT NOT NULL CHECK (tipo IN ('donacion', 'necesidad')),
    titulo TEXT NOT NULL CHECK (char_length(titulo) <= 80),
    descripcion TEXT NOT NULL CHECK (char_length(descripcion) <= 1000),
    categoria_id SMALLINT NOT NULL REFERENCES public.categorias(id),
    zona_id INT NOT NULL REFERENCES public.zonas(id),
    estado TEXT NOT NULL DEFAULT 'activa' CHECK (estado IN ('activa', 'en_proceso', 'completada')),
    urgencia TEXT CHECK (urgencia IN ('alta', 'media', 'sin_apuro')),
    estado_objeto TEXT CHECK (estado_objeto IN ('nuevo', 'como_nuevo', 'bueno', 'usado', 'requiere_reparacion')),
    cantidad SMALLINT NOT NULL DEFAULT 1 CHECK (cantidad >= 1),
    creada_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    vence_en TIMESTAMPTZ NOT NULL DEFAULT now() + interval '30 days',
    actualizada_en TIMESTAMPTZ,

    CONSTRAINT chk_coherencia_tipo CHECK (
        (tipo = 'necesidad' AND urgencia IS NOT NULL AND estado_objeto IS NULL) OR
        (tipo = 'donacion' AND estado_objeto IS NOT NULL AND urgencia IS NULL)
    )
);

-- RLS
ALTER TABLE public.publicaciones ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Ver publicaciones activas o propias"
  ON public.publicaciones
  FOR SELECT
  TO authenticated
  USING (estado IN ('activa', 'en_proceso') OR usuario_id = auth.uid());

CREATE POLICY "Insertar publicación propia"
  ON public.publicaciones
  FOR INSERT
  TO authenticated
  WITH CHECK (usuario_id = auth.uid());

CREATE POLICY "Actualizar publicación propia"
  ON public.publicaciones
  FOR UPDATE
  TO authenticated
  USING (usuario_id = auth.uid())
  WITH CHECK (usuario_id = auth.uid());

CREATE POLICY "Borrar publicación propia"
  ON public.publicaciones
  FOR DELETE
  TO authenticated
  USING (usuario_id = auth.uid());

GRANT SELECT, INSERT, UPDATE, DELETE ON public.publicaciones TO authenticated;